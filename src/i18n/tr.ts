export function t(path: string): string {
  const val = path.split('.').reduce(
    (o: unknown, k: string) =>
      o && typeof o === 'object' ? (o as Record<string, unknown>)[k] : undefined,
    tr as unknown
  );
  return typeof val === 'string' ? val : path;
}
